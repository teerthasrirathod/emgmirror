"""Self-contained HTML report for one session."""

from __future__ import annotations

import html
from pathlib import Path

import numpy as np
import plotly.graph_objects as go
from plotly.subplots import make_subplots

from .anatomy.figure import cross_section_figure, forearm_figure
from .processing.filters import clean_for_analysis, envelope
from .storage import Session

ARM_COLOR = {"right": "#3b6fb6", "left": "#d0582f"}


def signals_figure(session: Session, cfg: dict, max_points: int = 6000) -> go.Figure:
    fs = session.fs
    rows = sum(len(b.channels) for b in session.blocks)
    fig = make_subplots(rows=rows, cols=1, shared_xaxes=False, vertical_spacing=0.03,
                        subplot_titles=[f"{c.name} ({c.arm} {c.muscle})" for b in session.blocks for c in b.channels])
    r = 1
    for block in session.blocks:
        filt = clean_for_analysis(block.data, fs, cfg)
        env = envelope(filt, fs, cfg["processing"]["envelope_window_s"])
        step = max(1, len(filt) // max_points)
        t = np.arange(0, len(filt), step) / fs
        for c, ch in enumerate(block.channels):
            fig.add_trace(go.Scattergl(x=t, y=filt[::step, c], line=dict(width=0.6, color="#9aa4b1"),
                                       name="filtered", showlegend=False), row=r, col=1)
            fig.add_trace(go.Scattergl(x=t, y=env[::step, c], line=dict(width=1.6, color=ARM_COLOR[ch.arm]),
                                       name="envelope", showlegend=False), row=r, col=1)
            for tr in block.trials:
                if tr.task != "rest":
                    fig.add_vrect(x0=tr.start_s, x1=tr.end_s, fillcolor="#888", opacity=0.07, line_width=0,
                                  row=r, col=1)
            fig.update_yaxes(title_text="mV", row=r, col=1)
            r += 1
    fig.update_layout(height=180 * rows, margin=dict(l=50, r=10, t=30, b=30), paper_bgcolor="rgba(0,0,0,0)")
    return fig


def recruitment_figure(analysis: dict) -> go.Figure:
    groups = list(analysis.get("recruitment", {}))
    fig = make_subplots(rows=1, cols=max(len(groups), 1), subplot_titles=groups)
    for i, m in enumerate(groups, start=1):
        for arm, d in analysis["recruitment"][m].items():
            fig.add_trace(go.Scatter(x=d["level"], y=d["rms_net_mv"], mode="lines+markers", name=f"{arm}",
                                     line=dict(color=ARM_COLOR[arm]), showlegend=(i == 1)), row=1, col=i)
        fig.update_xaxes(title_text="target effort (fraction of max)", row=1, col=i)
        fig.update_yaxes(title_text="net RMS (mV)", row=1, col=i)
    fig.update_layout(height=340, margin=dict(l=50, r=10, t=40, b=40), paper_bgcolor="rgba(0,0,0,0)")
    return fig


def _summary_table(analysis: dict) -> str:
    def fmt(v):
        return "–" if v is None else f"{v:.0f}%"

    rows = []
    for m, s in analysis.get("summary", {}).items():
        gt = analysis.get("ground_truth_check", {}).get(m)
        truth = (f"<td>{gt['true_mu_pool_pct']:.0f}%</td><td>{gt['true_mu_firing_pct']:.0f}%</td>" if gt else "")
        rows.append(f"<tr><td>{html.escape(m)}</td><td>{fmt(s['activation_pct'])}</td>"
                    f"<td>{fmt(s['mu_firing_pct'])}</td>{truth}</tr>")
    truth_head = "<th>True pool (synthetic)</th><th>True firing (synthetic)</th>" if analysis.get("ground_truth_check") else ""
    return ("<table><tr><th>Muscle group</th><th>Activation (MVC RMS, % of right)</th>"
            f"<th>Firing motor units (experimental, % of right)</th>{truth_head}</tr>{''.join(rows)}</table>")


def write_report(session: Session, cfg: dict, analysis: dict, out: str | Path) -> Path:
    out = Path(out)
    anat, _ = forearm_figure(cfg, analysis.get("summary"))
    parts = [
        anat.to_html(full_html=False, include_plotlyjs="cdn"),
        recruitment_figure(analysis).to_html(full_html=False, include_plotlyjs=False),
        cross_section_figure(cfg, analysis.get("summary")).to_html(full_html=False, include_plotlyjs=False),
        signals_figure(session, cfg).to_html(full_html=False, include_plotlyjs=False),
    ]
    banner = ("<p class='warn'>SYNTHETIC DATA: generated by the motor-unit simulator. Not a measurement of "
              "a real person.</p>" if analysis.get("is_synthetic") else "")
    doc = f"""<!doctype html><html><head><meta charset="utf-8"><title>emgmirror report</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:1200px;margin:24px auto;padding:0 16px;color:#1d232b;background:#fafafa}}
table{{border-collapse:collapse;margin:12px 0}}td,th{{border:1px solid #ccd;padding:6px 10px;text-align:left}}
.warn{{background:#fff3cd;border:1px solid #e0c35c;padding:8px 12px}}
.note{{color:#555;font-size:14px}}
</style></head><body>
<h1>Forearm comparison: {html.escape(session.session_id)}</h1>
{banner}
<p class="note">Reference = right forearm (100%). Values are the left forearm relative to the right, same task,
same electrode placement. Research prototype, not a medical device or diagnosis.</p>
{_summary_table(analysis)}
<h2>3D forearm (template anatomy scaled to tape measurements)</h2>{parts[0]}
<h2>Cross-section at the muscle bellies (viewed from the hand)</h2>{parts[2]}
<h2>Recruitment during the slow grip ramp</h2>{parts[1]}
<h2>Signals</h2>{parts[3]}
</body></html>"""
    out.write_text(doc, encoding="utf-8")
    return out
